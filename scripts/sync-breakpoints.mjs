#!/usr/bin/env node
/**
 * Dessau — write the query-threshold table into the foundations page.
 *
 *   node scripts/sync-breakpoints.mjs
 *   node scripts/sync-breakpoints.mjs --check   # verify only, exit 1 if stale
 *
 * -----------------------------------------------------------------------------
 * Why this is generated rather than written
 * -----------------------------------------------------------------------------
 *
 * The foundations page documents which widths components actually switch at. That
 * table was hand-written once, and three of its six rows were wrong within the
 * hour: the content navigation was listed at 48rem when its query says 64rem, and
 * two rows named components that had nothing to do with the width beside them.
 *
 * Nothing caught it, because a wrong table looks exactly like a right one. Reading
 * it would have taught someone a threshold that does not exist, and they would have
 * had no reason to doubt it.
 *
 * So the derivable columns are derived. Width, container and file come from the
 * CSS every time this runs, and cannot disagree with it.
 *
 * The rationale — *why* 34rem and not 32rem — is not derivable, and it is the part
 * worth reading. It lives in the comment above each query, where it is maintained
 * next to the thing it explains, and this script pulls it from there rather than
 * asking for it to be written a second time.
 *
 * Zero dependencies, Node stdlib only.
 */

import { readFile, writeFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK_ONLY = process.argv.includes('--check');

const PAGE = join(ROOT, 'reference/foundations.html');
const START = '<!-- DDS_BREAKPOINT_TABLE:START — generated by scripts/sync-breakpoints.mjs. Do not edit. -->';
const END = '<!-- DDS_BREAKPOINT_TABLE:END -->';

/* ------------------------------------------------------------------ collect */

/**
 * The rationale for a threshold is the last sentence of the comment block directly
 * above the query — that is where it is written, because that is where it is read.
 *
 * Only a comment that is genuinely adjacent counts: anything further away is about
 * something else, and attributing it here would be worse than leaving the cell
 * empty.
 */
function rationaleFor(css, queryIndex) {
  const before = css.slice(0, queryIndex);
  const commentEnd = before.lastIndexOf('*/');
  if (commentEnd === -1) return null;

  // Adjacent means nothing but whitespace between the comment and the query.
  if (/[^\s]/.test(before.slice(commentEnd + 2))) return null;

  const commentStart = before.lastIndexOf('/*', commentEnd);
  if (commentStart === -1) return null;

  const text = before
    .slice(commentStart + 2, commentEnd)
    .replace(/^\s*\*+/gm, '')
    .replace(/\s+/g, ' ')
    .trim();

  if (!text) return null;

  /**
   * A section divider is adjacent to the query but says nothing about it. Without
   * this, `--- wide: a static column -----` was reported as the reason 64rem was
   * chosen — a cell that looks filled in and answers nothing, which is worse than
   * an empty one because it stops anyone asking.
   */
  const words = text.replace(/[-=*·—_]/g, ' ').trim();
  if (words.split(/\s+/).filter((w) => /[a-z]{3}/i.test(w)).length < 5) return null;

  return text;
}

const CSS_DIR = join(ROOT, 'dds/css');
const rows = [];

for (const name of (await readdir(CSS_DIR)).filter((n) => n.endsWith('.css'))) {
  const raw = await readFile(join(CSS_DIR, name), 'utf8');

  // Comments are stripped for matching but kept for the rationale lookup, so the
  // two passes use different copies of the same source.
  const pattern =
    /@(container|media)\s*([\w-]*)\s*\(\s*([^)]*?(?:inline-size|width)[^)]*?)\)/g;

  for (const match of raw.matchAll(pattern)) {
    const [, kind, container, condition] = match;

    // A comment discussing a query is not a query. `@media (min-width: var(...))`
    // appears in primitives.css purely as an example of what does not work.
    const inComment = (() => {
      const open = raw.lastIndexOf('/*', match.index);
      const close = raw.lastIndexOf('*/', match.index);
      return open > close;
    })();
    if (inComment) continue;

    const width = condition.match(/([\d.]+)(rem|px|em)/);
    if (!width) continue;

    rows.push({
      kind,
      container: container || null,
      condition: condition.trim().replace(/\s+/g, ' '),
      width: width[0],
      pixels: width[2] === 'rem' ? parseFloat(width[1]) * 16 : parseFloat(width[1]),
      file: name,
      rationale: rationaleFor(raw, match.index),
    });
  }
}

rows.sort((a, b) => a.pixels - b.pixels || a.file.localeCompare(b.file));

/* -------------------------------------------------------------------- render */

const escape = (text) =>
  String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/** Trim a rationale to its first sentence — the table is a summary, not the prose. */
function summarise(rationale) {
  if (!rationale) return '';
  const sentence = rationale.match(/^(.*?[.!])(\s|$)/);
  return escape(sentence ? sentence[1] : rationale.slice(0, 140));
}

const namedFromCss = [
  ...(await readFile(join(CSS_DIR, 'primitives.css'), 'utf8')).matchAll(
    /(--dds-breakpoint-[\w-]+)\s*:\s*([^;]+);/g
  ),
].map((m) => ({ name: m[1], pixels: parseFloat(m[2]) * 16 }));

const table = `${START}
          <div class="dds-scroll dds-mbs-sm">
            <table class="dds-table dds-text-sm">
              <caption class="dds-visually-hidden">
                Every width used in a container or media query, generated from the stylesheets
              </caption>
              <thead>
                <tr>
                  <th scope="col">Width</th>
                  <th scope="col">Query</th>
                  <th scope="col">Applies to</th>
                  <th scope="col">Why this width</th>
                </tr>
              </thead>
              <tbody>
${rows
  .map((row) => {
    const named = namedFromCss.find((n) => n.pixels === row.pixels);
    return `                <tr>
                  <td class="dds-numeric">${escape(row.width)}<br>
                    <span class="dds-text-2xs dds-text-muted">${row.pixels}px${
                      named ? ' · named' : ''
                    }</span></td>
                  <td><code class="dds-code">@${row.kind}${
                    row.container ? ' ' + escape(row.container) : ''
                  }</code></td>
                  <td class="dds-text-xs">${escape(row.file)}</td>
                  <td class="dds-text-xs dds-text-subtle">${summarise(row.rationale)}</td>
                </tr>`;
  })
  .join('\n')}
              </tbody>
            </table>
          </div>
          ${END}`;

/* --------------------------------------------------------------------- write */

const page = await readFile(PAGE, 'utf8');

const startAt = page.indexOf(START);
const endAt = page.indexOf(END);

if (startAt === -1 || endAt === -1) {
  console.error(
    `\nCannot run: reference/foundations.html has no generated block.\n\n` +
      `Add these two markers where the table belongs:\n\n` +
      `  ${START}\n  ${END}\n`
  );
  process.exit(1);
}

const updated = page.slice(0, startAt) + table + page.slice(endAt + END.length);

if (CHECK_ONLY) {
  if (updated === page) {
    console.log(`reference/foundations.html breakpoint table is current (${rows.length} rows).`);
    process.exit(0);
  }
  console.error(
    'reference/foundations.html breakpoint table is STALE — ' +
      'run: node scripts/sync-breakpoints.mjs'
  );
  process.exit(1);
}

await writeFile(PAGE, updated, 'utf8');

const missing = rows.filter((row) => !row.rationale);

console.log(
  `Wrote the breakpoint table into reference/foundations.html — ${rows.length} thresholds.`
);

if (missing.length) {
  console.log(
    `\n${missing.length} threshold(s) have no comment above them, so the page cannot ` +
      `explain why they were chosen:\n`
  );
  for (const row of missing) {
    console.log(`  ${row.width.padEnd(7)} @${row.kind} ${row.container ?? ''} — ${row.file}`);
  }
  console.log('\nA threshold with no stated reason is a number nobody can safely change.');
}
