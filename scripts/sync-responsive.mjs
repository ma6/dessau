#!/usr/bin/env node
/**
 * Dessau — write each component's narrow-width behaviour into the specifications.
 *
 *   node scripts/sync-responsive.mjs
 *   node scripts/sync-responsive.mjs --check   # verify only, exit 1 if stale
 *
 * -----------------------------------------------------------------------------
 * Why this is generated rather than written
 * -----------------------------------------------------------------------------
 *
 * "What does this component do at 320px?" now has an answer per entry in
 * `agent/index.json`, and `check-agent-index.mjs` verifies the falsifiable half of
 * it against the CSS (#74). The rendered pages carry the same answer as a
 * `.ref-note` beside each specimen, which `check-reference.mjs` requires of every
 * component that changes shape by width (#78).
 *
 * `agent/components.md` and `agent/patterns.md` are the third place a reader looks
 * — they are what `AGENTS.md` sends anyone to for a component's contract — and
 * writing the same sentence there by hand would be a third copy that nothing
 * checks. In a repository whose argument is that the second copy of anything
 * eventually becomes the wrong copy, that is not a small objection.
 *
 * So the specification carries the answer without owning it. This script writes it
 * from the index between markers, the same way the breakpoint table on the
 * foundations page is written from the stylesheets. One source, three readers.
 *
 * What is NOT generated: the prose in each component's own section. A sentence
 * about wrapping written where it belongs, beside the contract it affects, is
 * worth more than a row in a table — this table is the index nobody has to open,
 * not a replacement for saying what a component does.
 *
 * Zero dependencies, Node stdlib only.
 * @catches A specification whose responsive summary no longer matches the index.
 *
 */

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK_ONLY = process.argv.includes('--check');

const START =
  '<!-- DDS_RESPONSIVE_TABLE:START — generated by scripts/sync-responsive.mjs. Do not edit. -->';
const END = '<!-- DDS_RESPONSIVE_TABLE:END -->';

const index = JSON.parse(await readFile(join(ROOT, 'agent/index.json'), 'utf8'));

/**
 * The four kinds, in the order a reader wants them.
 *
 * The ones with a threshold first, because those are the ones somebody is looking
 * for. `none` last and counted rather than listed in full — thirty-eight rows
 * saying "nothing changes" would bury the ten that do.
 */
const ORDER = ['container', 'viewport', 'self', 'none'];

const KIND_WORDS = {
  container: 'Responds to its container',
  viewport: 'Depends on the device',
  self: 'Adapts by itself, with no threshold',
  none: 'Nothing changes with width',
};

function table(entries) {
  const byKind = new Map(ORDER.map((kind) => [kind, []]));

  for (const entry of entries) {
    const value = entry.responsive || '';
    const kind = value.split(' — ')[0].trim();
    const detail = value.slice(kind.length + 3).trim();
    if (!byKind.has(kind)) continue;
    byKind.get(kind).push({ name: entry.name, detail });
  }

  const lines = [];

  for (const kind of ORDER) {
    const rows = byKind.get(kind).sort((a, b) => a.name.localeCompare(b.name));
    if (!rows.length) continue;

    lines.push('', `**${KIND_WORDS[kind]}** — ${rows.length}`, '');

    if (kind === 'none') {
      // A list rather than a table: there is nothing to say per row.
      lines.push(rows.map((row) => `\`${row.name}\``).join(' · '));
      continue;
    }

    lines.push('| | |', '| --- | --- |');
    for (const row of rows) {
      lines.push(`| \`${row.name}\` | ${row.detail} |`);
    }
  }

  return lines.join('\n');
}

const PREAMBLE = [
  '',
  '## What each of these does at 320px',
  '',
  'Generated from [`index.json`](index.json), which is where the answer lives and',
  'where `scripts/check-agent-index.mjs` verifies it against the CSS. A claim of a',
  'query must be backed by one; a claim that nothing changes must not be.',
  '',
  'The behaviour itself is described where it belongs — beside the component, and in',
  'a `.ref-note` on the rendered page. This is the index of it.',
].join('\n');

const targets = [
  { file: 'agent/components.md', entries: index.components },
  { file: 'agent/patterns.md', entries: index.patterns },
];

let stale = 0;

for (const target of targets) {
  const path = join(ROOT, target.file);
  const source = await readFile(path, 'utf8');

  const from = source.indexOf(START);
  const to = source.indexOf(END);

  if (from === -1 || to === -1) {
    console.error(
      `${target.file} has no ${START.match(/DDS_[A-Z_]+/)[0]} markers — add them where the table belongs`
    );
    process.exit(1);
  }

  const generated = `${START}\n${PREAMBLE}\n${table(target.entries)}\n${END}`;
  const next = source.slice(0, from) + generated + source.slice(to + END.length);

  if (next === source) {
    console.log(`  ${target.file} is current`);
    continue;
  }

  stale += 1;
  if (CHECK_ONLY) {
    console.error(`${target.file} is STALE — run: node scripts/sync-responsive.mjs`);
  } else {
    await writeFile(path, next);
    console.log(`  ${target.file} updated`);
  }
}

if (CHECK_ONLY && stale) process.exit(1);

console.log(
  `\n${index.components.length + index.patterns.length} entries summarised across ` +
    `${targets.length} specifications.`
);
