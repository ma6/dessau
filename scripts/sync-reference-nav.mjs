#!/usr/bin/env node
/**
 * Dessau — write the reference site navigation into every page.
 *
 *   node scripts/sync-reference-nav.mjs
 *   node scripts/sync-reference-nav.mjs --check   # verify only, exit 1 if stale
 *
 * -----------------------------------------------------------------------------
 * Why this is generated
 * -----------------------------------------------------------------------------
 *
 * The same navigation appears in the header of every reference page, and it was
 * hand-written in each. With six pages that was tolerable; eight made it eight copies
 * of one list, and the failure is asymmetric — a page missing from the nav is a page
 * nobody can reach, while the page itself looks perfectly fine.
 *
 * Worse, it fails *per page*: forget to update one file and seven navigations agree
 * while the eighth quietly omits an entry. Nothing looks broken from any single page.
 *
 * -----------------------------------------------------------------------------
 * Two levels, and why the second one is a visible row rather than a dropdown
 * -----------------------------------------------------------------------------
 *
 * Eight items on one level is a list to read rather than a structure to navigate, and
 * it flattens away the fact that three of the pages are one catalogue split in three.
 *
 * The second level is a second row, always visible, showing the current group's pages.
 * A dropdown would be more compact and worse: it hides the structure behind a click,
 * it needs interaction to answer "where am I", and it puts a menu widget between the
 * reader and a link. A visible row costs one line of header and needs no JavaScript at
 * all — nothing to fail, nothing to announce, nothing to trap focus in.
 *
 * A group whose only child is itself gets no second row, because a row of one is not a
 * choice.
 *
 * @catches A reference page missing from the site navigation, an entry pointing at a
 *   page that does not exist, a page in reference/ that no group claims, and a wrong
 *   or missing `aria-current="page"`.
 *
 * Zero dependencies, Node stdlib only.
 */

import { readFile, writeFile, readdir, access } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK_ONLY = process.argv.includes('--check');

const REFERENCE = join(ROOT, 'reference');
const START = '<!-- REF_NAV:START — generated by scripts/sync-reference-nav.mjs. Do not edit. -->';
const END = '<!-- REF_NAV:END -->';

/**
 * The structure, in reading order.
 *
 * Not alphabetical and not the order the files were written. It follows the layer
 * model: what Dessau is, then the rules everything is measured against, then the
 * catalogue built on them, then the compositions, then how to write in it. Someone
 * reading front to back meets each idea after the ones it depends on.
 *
 * The three-way split of the catalogue is not arbitrary either — it is the split that
 * already exists in the stylesheets (`components.css`, `components-content.css`,
 * `components-navigation.css`), so the navigation matches the thing it describes.
 */
const STRUCTURE = [
  { label: 'Overview', file: 'index.html' },
  {
    label: 'Foundations',
    children: [
      { label: 'Values', file: 'foundations.html' },
      { label: 'Architecture', file: 'architecture.html' },
    ],
  },
  {
    label: 'Components',
    children: [
      { label: 'Controls', file: 'components.html' },
      { label: 'Content', file: 'content.html' },
      { label: 'Navigation', file: 'navigation.html' },
    ],
  },
  { label: 'Patterns', file: 'patterns.html' },
  { label: 'Writing', file: 'writing.html' },
];

/* ------------------------------------------------------------------- checks */

const problems = [];

/** Flatten to `{ file, label, group }` for every page the navigation reaches. */
const pages = [];
for (const entry of STRUCTURE) {
  if (entry.file) {
    pages.push({ ...entry, group: entry });
    continue;
  }
  for (const child of entry.children) {
    pages.push({ ...child, group: entry });
  }
}

for (const page of pages) {
  try {
    await access(join(REFERENCE, page.file));
  } catch {
    problems.push(`the navigation lists reference/${page.file}, which does not exist`);
  }
}

/**
 * The other direction. A page in `reference/` that no group claims is unreachable
 * from every other page — and it is the likelier mistake, because writing a page and
 * forgetting the navigation leaves the page itself looking finished.
 */
const onDisk = (await readdir(REFERENCE)).filter((name) => name.endsWith('.html'));
for (const name of onDisk) {
  if (!pages.some((page) => page.file === name)) {
    problems.push(
      `reference/${name} exists but no group in STRUCTURE claims it, so nothing links ` +
        `to it — add it to scripts/sync-reference-nav.mjs`
    );
  }
}

if (problems.length) {
  console.error('');
  for (const problem of problems) console.error(`  ${problem}`);
  console.error('');
  process.exit(1);
}

/* -------------------------------------------------------------------- render */

/** The page a group entry points at: its first child. */
const entryPoint = (entry) => entry.file ?? entry.children[0].file;

function navigationFor(page) {
  const primary = STRUCTURE.map((entry) => {
    const isCurrentSection = entry === page.group;

    /**
     * `data-current-section`, not `aria-current`.
     *
     * The group is not a page, so nobody is "on" it — and the second row below already
     * names where the reader is, with `aria-current="page"` on the actual page. Marking
     * the ancestor as well would put two current items in one header for a
     * screen-reader user to reconcile.
     *
     * The visual treatment is weight plus colour plus an underline, and it is
     * deliberately redundant with the second row rather than the only signal.
     */
    const marker = isCurrentSection ? ' data-current-section' : '';

    // A leaf that IS the current page carries the real ARIA state.
    const current = entry.file === page.file ? ' aria-current="page"' : '';

    return `            <a href="${entryPoint(entry)}"${current}${marker}>${entry.label}</a>`;
  }).join('\n');

  let secondary = '';

  // A row of one is not a choice.
  if (page.group.children && page.group.children.length > 1) {
    const links = page.group.children
      .map((child) => {
        const current = child.file === page.file ? ' aria-current="page"' : '';
        return `            <a href="${child.file}"${current}>${child.label}</a>`;
      })
      .join('\n');

    secondary =
      `\n        <nav class="ref-nav-secondary" aria-label="${page.group.label} pages">\n` +
      `${links}\n` +
      `        </nav>`;
  }

  /**
   * A disclosure below the shell's threshold, both rows inline above it.
   *
   * The behaviour is `data-dds-nav-toggle` from `components-navigation.js` — the same
   * enhancement the site header component uses. Reusing it rather than writing a second
   * collapsing navigation means the reference exercises the real code on every page, and
   * that it already handles the trap: it watches whether the toggle is displayed and
   * clears `hidden` once the rows are inline, so resizing a window while collapsed
   * cannot leave the navigation unreachable.
   *
   * Without JavaScript the panel is `hidden` below the threshold and the button does
   * nothing — so the markup ships with the panel NOT hidden, and the CSS hides it only
   * where the toggle is actually shown. Failing open is the right direction: a
   * navigation that is always visible is a worse layout, and one that cannot be opened
   * is a dead end.
   */
  return (
    `\n      <button class="ref-nav-toggle dds-button dds-button-secondary" type="button"\n` +
    `              data-dds-nav-toggle="ref-nav-panel"\n` +
    `              aria-expanded="false" aria-controls="ref-nav-panel">\n` +
    `        <svg class="dds-icon" aria-hidden="true" focusable="false"><use href="#dds-icon-menu"/></svg>\n` +
    `        Menu\n` +
    `      </button>\n\n` +
    `      <div class="ref-nav-panel" id="ref-nav-panel">\n` +
    `        <nav class="ref-nav" aria-label="Reference">\n` +
    `${primary}\n` +
    `        </nav>${secondary}\n` +
    `      </div>\n      `
  );
}

/* --------------------------------------------------------------------- write */

let updated = 0;
const stale = [];

for (const page of pages) {
  const path = join(REFERENCE, page.file);
  const source = await readFile(path, 'utf8');

  const startAt = source.indexOf(START);
  const endAt = source.indexOf(END);

  if (startAt === -1 || endAt === -1) {
    problems.push(
      `reference/${page.file} has no REF_NAV block — add these two markers where the ` +
        `header navigation belongs:\n      ${START}\n      ${END}`
    );
    continue;
  }

  const block = START + navigationFor(page) + END;
  const next = source.slice(0, startAt) + block + source.slice(endAt + END.length);

  if (next === source) continue;

  if (CHECK_ONLY) {
    stale.push(page.file);
    continue;
  }

  await writeFile(path, next, 'utf8');
  updated += 1;
  console.log(`  updated reference/${page.file}`);
}

if (problems.length) {
  console.error('');
  for (const problem of problems) console.error(`  ${problem}`);
  console.error('');
  process.exit(1);
}

if (CHECK_ONLY) {
  if (!stale.length) {
    console.log(`Reference navigation is current in all ${pages.length} pages.`);
    process.exit(0);
  }
  console.error(
    `Reference navigation is STALE in ${stale.join(', ')} — ` +
      `run: node scripts/sync-reference-nav.mjs`
  );
  process.exit(1);
}

console.log(
  `\n${pages.length} pages in ${STRUCTURE.length} top-level entries, ${updated} updated.`
);
