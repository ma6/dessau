#!/usr/bin/env node
/**
 * Dessau — write the reference site navigation into every page.
 *
 *   node scripts/sync-reference-nav.mjs
 *   node scripts/sync-reference-nav.mjs --check   # verify only, exit 1 if stale
 *
 * -----------------------------------------------------------------------------
 * Why this is generated
 * -----------------------------------------------------------------------------
 *
 * The same navigation appears in the header of every reference page, and it was
 * hand-written in each. With six pages that was tolerable; adding two made it eight
 * copies of one list, and the failure is asymmetric — a page missing from the nav is
 * a page nobody can reach, while the page itself looks perfectly fine.
 *
 * Worse, it fails *per page*: forget to update one file and seven navigations agree
 * while the eighth quietly omits an entry. Nothing looks broken from any single page.
 *
 * So the order lives here, once, and `aria-current="page"` is derived from which file
 * is being written — which is the part most likely to be copied wrongly by hand.
 *
 * @catches A reference page missing from the site navigation, an entry pointing at a
 *   page that does not exist, and a wrong or missing `aria-current="page"`.
 *
 * Zero dependencies, Node stdlib only.
 */

import { readFile, writeFile, access } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK_ONLY = process.argv.includes('--check');

const REFERENCE = join(ROOT, 'reference');
const START = '<!-- REF_NAV:START — generated by scripts/sync-reference-nav.mjs. Do not edit. -->';
const END = '<!-- REF_NAV:END -->';

/**
 * The navigation, in reading order.
 *
 * Not alphabetical and not the order the files were written. It follows the layer
 * model: what Dessau is, then the values, then how it is put together, then the
 * things built from it, then how to write in it. Someone reading the reference
 * front to back should meet each idea after the ones it depends on.
 */
const PAGES = [
  { file: 'index.html', label: 'Overview' },
  { file: 'foundations.html', label: 'Foundations' },
  { file: 'architecture.html', label: 'Architecture' },
  { file: 'components.html', label: 'Components' },
  { file: 'content.html', label: 'Content' },
  { file: 'navigation.html', label: 'Navigation' },
  { file: 'patterns.html', label: 'Patterns' },
  { file: 'writing.html', label: 'Writing' },
];

/* ------------------------------------------------------------------- checks */

const problems = [];

for (const page of PAGES) {
  try {
    await access(join(REFERENCE, page.file));
  } catch {
    problems.push(`the navigation lists reference/${page.file}, which does not exist`);
  }
}

if (problems.length) {
  console.error('');
  for (const problem of problems) console.error(`  ${problem}`);
  console.error('');
  process.exit(1);
}

/* -------------------------------------------------------------------- write */

let updated = 0;
let stale = [];

for (const page of PAGES) {
  const path = join(REFERENCE, page.file);
  const source = await readFile(path, 'utf8');

  const startAt = source.indexOf(START);
  const endAt = source.indexOf(END);

  if (startAt === -1 || endAt === -1) {
    problems.push(
      `reference/${page.file} has no REF_NAV block — add these two markers inside ` +
        `its <nav class="ref-nav">:\n      ${START}\n      ${END}`
    );
    continue;
  }

  const links = PAGES.map((entry) => {
    // The current page is marked, and marked only here — deriving it from the file
    // being written is what stops a copied header claiming the wrong page.
    const current = entry.file === page.file ? ' aria-current="page"' : '';
    return `        <a href="${entry.file}"${current}>${entry.label}</a>`;
  }).join('\n');

  const block = `${START}\n${links}\n        ${END}`;

  const next = source.slice(0, startAt) + block + source.slice(endAt + END.length);

  if (next === source) continue;

  if (CHECK_ONLY) {
    stale.push(page.file);
    continue;
  }

  await writeFile(path, next, 'utf8');
  updated += 1;
  console.log(`  updated reference/${page.file}`);
}

if (problems.length) {
  console.error('');
  for (const problem of problems) console.error(`  ${problem}`);
  console.error('');
  process.exit(1);
}

if (CHECK_ONLY) {
  if (!stale.length) {
    console.log(`Reference navigation is current in all ${PAGES.length} pages.`);
    process.exit(0);
  }
  console.error(
    `Reference navigation is STALE in ${stale.join(', ')} — ` +
      `run: node scripts/sync-reference-nav.mjs`
  );
  process.exit(1);
}

console.log(`\n${PAGES.length} pages, ${updated} updated.`);
