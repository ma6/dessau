#!/usr/bin/env node
/**
 * Dessau — build the side navigation on every reference page.
 *
 *   node scripts/sync-reference-toc.mjs
 *   node scripts/sync-reference-toc.mjs --check   # verify only, exit 1 if stale
 *
 * Each reference page gets an "On this page" list beside its content, generated
 * from that page's own `<section class="ref-section" id="…">` headings.
 *
 * -----------------------------------------------------------------------------
 * Why generated rather than written by hand
 * -----------------------------------------------------------------------------
 *
 * A hand-maintained contents list is a second copy of the page's structure. It
 * goes stale the first time a section is renamed, and a contents list that points
 * at the wrong thing is worse than none — it is actively misleading, and it is
 * the kind of error nobody notices because nobody re-reads their own navigation.
 *
 * Generating it makes the page the single source of truth, and `--check` turns a
 * stale list into a failure rather than a surprise.
 *
 * The script also inserts the two-column wrapper on first run, so adding a side
 * navigation to a new page requires nothing but the section markup.
 *
 * Zero dependencies, Node stdlib only.
 * @catches A stale "On this page" navigation, when run with `--check`.
 *
 */

import { readFile, writeFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const REFERENCE_DIR = join(ROOT, 'reference');
const CHECK_ONLY = process.argv.includes('--check');

const TOC_START = '<!-- REF_TOC:START — generated by scripts/sync-reference-toc.mjs. Do not edit. -->';
const TOC_END = '<!-- REF_TOC:END -->';

/** The divider that separates every page's intro from its sections. */
const DIVIDER = '<hr class="dds-divider dds-mbs-2xl dds-mbe-2xl">';

/** Strip tags and collapse whitespace, to turn a heading into link text. */
function textOf(html) {
  return html
    .replace(/<[^>]+>/g, '')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&nbsp;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Find every `<section class="ref-section" id="…">` and its first `<h2>`.
 *
 * A regex is enough because these files are generated and reviewed by us, and
 * the alternative is a DOM parser dependency for a job with exactly one shape.
 */
function sectionsOf(html) {
  const sections = [];
  const pattern = /<section\b[^>]*class="[^"]*\bref-section\b[^"]*"[^>]*\bid="([^"]+)"[^>]*>/g;

  let match;
  while ((match = pattern.exec(html)) !== null) {
    const id = match[1];
    // Look for the first h2 after the opening tag, but not past the next
    // section — a section with no h2 should be skipped, not borrow the next one's.
    const rest = html.slice(match.index + match[0].length);
    const nextSection = rest.search(/<section\b[^>]*class="[^"]*\bref-section\b/);
    const scope = nextSection === -1 ? rest : rest.slice(0, nextSection);

    const heading = scope.match(/<h2\b[^>]*>([\s\S]*?)<\/h2>/);
    if (!heading) continue;

    sections.push({ id, title: textOf(heading[1]) });
  }

  return sections;
}

function buildList(sections, indent) {
  const pad = ' '.repeat(indent);
  const items = sections
    .map((section) => `${pad}  <li><a href="#${section.id}">${section.title}</a></li>`)
    .join('\n');
  return `${pad}<ul>\n${items}\n${pad}</ul>`;
}

/**
 * Wrap the page's sections in the two-column layout, if it is not wrapped yet.
 *
 * Idempotent: a page that already has the wrapper is left alone, so the script
 * can be run any number of times.
 */
function ensureWrapper(html, pageTitle) {
  if (html.includes('class="ref-layout"')) return html;

  const dividerIndex = html.indexOf(DIVIDER);
  if (dividerIndex === -1) {
    return null; // not a reference content page
  }

  const afterDivider = dividerIndex + DIVIDER.length;

  // The sections run from just after the divider to the container's closing tag.
  const tail = '\n    </div>\n  </main>';
  const tailIndex = html.lastIndexOf(tail);
  if (tailIndex === -1 || tailIndex < afterDivider) return null;

  const before = html.slice(0, afterDivider);
  const body = html.slice(afterDivider, tailIndex);
  const after = html.slice(tailIndex);

  const tocId = 'page-toc-title';

  const opening = `

      <div class="ref-layout">
        <aside class="ref-aside">
          <nav class="dds-toc" data-dds-toc aria-labelledby="${tocId}">
            <p class="dds-toc-title" id="${tocId}">On this page</p>
            ${TOC_START}
            ${TOC_END}
          </nav>
        </aside>

        <div class="ref-content">`;

  const closing = `
        </div>
      </div>`;

  return before + opening + body + closing + after;
}

const files = (await readdir(REFERENCE_DIR, { withFileTypes: true }))
  .filter((entry) => entry.isFile() && entry.name.endsWith('.html'))
  .map((entry) => join(REFERENCE_DIR, entry.name))
  .sort();

let updated = 0;
let stale = 0;
let skipped = 0;

for (const file of files) {
  const original = await readFile(file, 'utf8');
  const shortPath = relative(ROOT, file);

  const wrapped = ensureWrapper(original, shortPath);
  if (wrapped === null) {
    console.warn(`  skipped (no section layout): ${shortPath}`);
    skipped++;
    continue;
  }

  const sections = sectionsOf(wrapped);
  if (!sections.length) {
    console.warn(`  skipped (no sections found): ${shortPath}`);
    skipped++;
    continue;
  }

  const startIndex = wrapped.indexOf(TOC_START);
  const endIndex = wrapped.indexOf(TOC_END);
  if (startIndex === -1 || endIndex === -1) {
    console.warn(`  skipped (no TOC markers): ${shortPath}`);
    skipped++;
    continue;
  }

  const next =
    wrapped.slice(0, startIndex + TOC_START.length) +
    '\n' +
    buildList(sections, 12) +
    '\n            ' +
    wrapped.slice(endIndex);

  if (next === original) continue;

  if (CHECK_ONLY) {
    console.error(`  STALE ${shortPath}`);
    stale++;
  } else {
    await writeFile(file, next, 'utf8');
    console.log(`  updated ${shortPath} (${sections.length} sections)`);
    updated++;
  }
}

console.log(
  `\n${files.length} reference pages scanned.` +
    (CHECK_ONLY
      ? stale === 0
        ? ' All side navigations are current.'
        : ` ${stale} STALE.`
      : ` ${updated} updated.`) +
    (skipped ? ` ${skipped} skipped.` : '')
);

process.exit(stale === 0 ? 0 : 1);
